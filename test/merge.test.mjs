import fs from 'node:fs';
import assert from 'node:assert';
import { analyze } from '../src/importer/index.js';
import { mergeImport } from '../src/importer/merge.js';
const res = analyze(JSON.parse(fs.readFileSync('workbook.json','utf8')), { today:'2026-10-24' });
const db = { vehicles:[], drivers:[], clients:[], rentals:[], expenses:[], accounts:[], loans:[], insurance:[], chama:[], nextId:1, settings:{} };
const log1 = mergeImport(db, res, { today:'2026-10-24' });
console.log(log1.added, 'unmatched allowances', log1.unmatchedAllowances.length);
const n = { r: db.rentals.length, e: db.expenses.length };
const log2 = mergeImport(db, res, { today:'2026-10-24' });
assert.deepEqual(n, { r: db.rentals.length, e: db.expenses.length }, 'second import must add nothing');
assert.equal(new Set(db.vehicles.map(v=>v.reg)).size, db.vehicles.length);
assert.equal(new Set(db.rentals.map(r=>r.id).concat(db.expenses.map(e=>e.id))).size, db.rentals.length+db.expenses.length);
console.log('second run skipped', log2.skipped);
const billed = db.rentals.reduce((s,r)=>s+r.amount,0); console.log('billed', billed, 'allowance on rentals', db.rentals.reduce((s,r)=>s+r.allowance,0));
console.log('types', db.rentals.reduce((a,r)=>(a[r.type]=(a[r.type]||0)+1,a),{}));
console.log('expense by category', db.expenses.reduce((a,x)=>(a[x.category]=Math.round((a[x.category]||0)+x.amount),a),{}));
console.log('merge ok');
import { statement } from '../src/statement.js';
const types = db.clients.reduce((a,c)=>(a[c.type]=(a[c.type]||0)+1,a),{});
console.log('client types', types, 'rentals without client', db.rentals.filter(r=>!r.clientId).length);
console.log('account lines', db.accounts.length, 'standing', JSON.stringify(db.settings.standingExpenses));
assert.equal(db.settings.standingExpenses.length, 1);
const w = db.clients.find(c=>c.name==='KANINI'); console.log('walk-in sample', w && [w.type,w.phone,w.area,w.usualReg,w.driverName].join(' | '));
const c1 = db.rentals.find(r=>r.type==='coop' && r.clientId); console.log('coop rental sample', c1 && [db.clients.find(c=>c.id===c1.clientId).name, c1.contract, c1.pickup, c1.amount].join(' | '));
assert.deepEqual(statement([{month:0,bf:100,entries:[{amount:50},{amount:-30}],sheetTotal:120},{month:1,bf:999,entries:[{amount:-20}],sheetTotal:100}]).map(x=>[x.opening,x.closing,x.bfDiff]), [[100,120,0],[120,100,-879]]);
console.log('statement ok');
