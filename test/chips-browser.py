# run: cd fleetpilot-update && python3 -m http.server 8765 &   then   python3 test/chips-browser.py
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page()
    pg.goto('http://localhost:8765/test/chips-harness.html'); pg.wait_for_function('window.ready'); pg.wait_for_timeout(300)
    print('errors:', pg.evaluate('window.errs'))
    def chips(scope, group): return pg.eval_on_selector_all(f'[data-chip="{scope}"][data-group="{group}"]', 'els=>els.map(e=>e.textContent+(e.classList.contains("on")?"*":""))')
    print('fuel view', chips('fuel','view'))
    print('audit src', chips('fuelaudit','src'), chips('fuelaudit','rtype'))
    rows = lambda: pg.locator('#fu_table tbody tr[data-id]').count()
    print('fills shown (month=all?)', pg.locator('#fu_month').input_value(), rows())
    pg.select_option('#fu_month','all'); pg.wait_for_timeout(100)
    print('all months rows', rows(), chips('fuel','view'))
    pg.click('[data-chip="fuel"][data-key="Mixed"]'); print('Mixed fills rows', rows(), 'tags', pg.locator('#fu_table .tag').count(), chips('fuel','view'))
    pg.click('[data-chip="fuel"][data-key="Mixed"]'); print('tap again clears', rows())
    pg.click('[data-chip="fuel"][data-key="Ola"]'); print('Ola', rows(), 'select', pg.locator('#fu_acc').input_value())
    pg.click('[data-chip="fuel"][data-key="none"]'); print('Untagged', rows())
    pg.click('[data-chip="fuelaudit"][data-group="src"][data-key="Mixed"]'); print('audit Mixed rows', pg.locator('#fu_audit tbody tr[data-open]').count(), chips('fuelaudit','rtype'))
    print('perf', chips('perf','type'), chips('perf','src'), chips('perf','hire'))
    n = lambda: pg.locator('#panel-performance table').first.locator('tbody tr[data-rid]').count()
    print('perf rows', n()); pg.click('[data-chip="perf"][data-group="src"][data-key="Mixed"]'); print('perf Mixed', n(), chips('perf','type'))
    pg.click('[data-chip="perf"][data-group="src"][data-key="Mixed"]'); pg.click('[data-chip="perf"][data-group="hire"][data-key="sub"]'); print('perf sub-hire', n())
    print('sub', chips('subhire','fStatus'), chips('subhire','fKind'), chips('subhire','fDriver'))
    pg.click('[data-chip="subhire"][data-group="fDriver"][data-key="without"]'); print('sub no driver rows', pg.locator('#sh_table tbody tr[data-id]').count())
    pg.click('[data-chip="subhire"][data-group="fStatus"][data-key="notcleared"]'); print('sub notcleared rows', pg.locator('#sh_table tbody tr[data-id]').count())
    print('errors end:', pg.evaluate('window.errs'))
    b.close()
